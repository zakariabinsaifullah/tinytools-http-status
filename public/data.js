export const STATUSES = [
  ...REGISTERED.map(([code, phrase, rfc, section, desc, extra = {}]) => ({
    code,
    phrase,
    cls: Math.floor(code / 100),
    desc,
    ref: `RFC ${rfc} §${section}`,
    url: rfcUrl(rfc, section),
    cacheable: CACHEABLE.has(code),
    status: extra.status || null,
    tags: extra.tags || [],
    aka: extra.aka || [],
    note: extra.note || null,
    unofficial: false,
    source: null,
  })),
  ...UNOFFICIAL.map(([code, phrase, source, desc, url = null]) => ({
    code,
    phrase,
    cls: Math.floor(code / 100),
    desc,
    ref: url ? `${source} docs` : null,
    url,
    cacheable: false,
    status: null,
    tags: [],
    aka: [],
    note: null,
    unofficial: true,
    source,
  })),
].sort((a, b) => a.code - b.code || Number(a.unofficial) - Number(b.unofficial));
